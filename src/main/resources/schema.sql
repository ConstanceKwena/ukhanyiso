-- Ukhanyiso data model, compatible with H2 and PostgreSQL.
-- Rule: every fact a learner can see (APS, subject, date) points to a row in `sources`.
-- PostgreSQL note: H2-specific types used here (IDENTITY, INTEGER booleans) work on both
-- engines; if you use PostgreSQL, run this schema once with spring.sql.init.mode=always
-- and set it to never afterwards to keep the catalogue refresh from re-running.

CREATE TABLE IF NOT EXISTS sources (
    source_id        VARCHAR(20)   PRIMARY KEY,
    institution_id   VARCHAR(20),
    course_id        VARCHAR(40),                      -- NULL for institution-level facts
    field            VARCHAR(40)   NOT NULL,           -- 'min_aps' | 'closing_date' | 'aps_method'
    value_recorded   VARCHAR(2000) NOT NULL,
    official_link    VARCHAR(500)  NOT NULL,
    source_type      VARCHAR(20)   NOT NULL,           -- 'official' | 'secondary' | 'none'
    date_checked     DATE          NOT NULL,
    checked_by       VARCHAR(100)  NOT NULL,
    status           VARCHAR(20)   NOT NULL            -- 'verified' | 'partial' | 'unverified' | 'conflicting' | 'stale'
);

CREATE TABLE IF NOT EXISTS institutions (
    institution_id       VARCHAR(20)  PRIMARY KEY,     -- 'UJ', 'UP', 'TUT'
    name                 VARCHAR(255) NOT NULL,
    inst_type            VARCHAR(40)  NOT NULL,        -- 'university' | 'university_of_technology' | 'tvet_college'
    aps_method           VARCHAR(30)  NOT NULL,        -- 'BEST6_EXCL_LO' | 'ALL_EXCL_LO' | 'NO_APS' | 'CUSTOM'
    aps_method_verified  INTEGER      NOT NULL DEFAULT 0,
    aps_method_note      VARCHAR(500),
    apply_url            VARCHAR(500) NOT NULL,
    app_fee_rand         INTEGER,
    source_id            VARCHAR(20)  REFERENCES sources(source_id),
    exclude_level_one    INTEGER      NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS courses (
    course_id        VARCHAR(40)  PRIMARY KEY,
    institution_id   VARCHAR(20)  NOT NULL REFERENCES institutions(institution_id),
    name             VARCHAR(255) NOT NULL,
    course_code      VARCHAR(40),
    qualification    VARCHAR(30)  NOT NULL,
    faculty          VARCHAR(255),
    min_aps          INTEGER,
    closing_date     DATE,
    closing_time     TIME,
    course_url       VARCHAR(500) NOT NULL,
    intake_year      INTEGER      NOT NULL,
    source_id        VARCHAR(20)  NOT NULL REFERENCES sources(source_id)
);

CREATE TABLE IF NOT EXISTS subjects (
    subject_id       VARCHAR(20)  PRIMARY KEY,
    name             VARCHAR(255) NOT NULL,
    counts_in_aps    INTEGER      NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS course_requirements (
    req_id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id        VARCHAR(40) NOT NULL REFERENCES courses(course_id),
    group_id         INTEGER     NOT NULL,
    subject_id       VARCHAR(20) NOT NULL REFERENCES subjects(subject_id),
    min_level        INTEGER     NOT NULL CHECK (min_level BETWEEN 1 AND 7),
    aps_required     INTEGER,
    min_percent      INTEGER,
    source_id        VARCHAR(20) NOT NULL REFERENCES sources(source_id)
);

CREATE TABLE IF NOT EXISTS match_config (
    aps_tolerance        INTEGER NOT NULL DEFAULT 2,
    level_tolerance      INTEGER NOT NULL DEFAULT 1,
    max_gaps_for_near    INTEGER NOT NULL DEFAULT 1,
    closing_soon_days    INTEGER NOT NULL DEFAULT 14,
    likely_aps_margin    INTEGER NOT NULL DEFAULT 3
);

CREATE TABLE IF NOT EXISTS app_users (
    user_id       VARCHAR(100) PRIMARY KEY,   -- the learner's email address
    display_name  VARCHAR(100) NOT NULL,
    password_salt VARCHAR(64) NOT NULL,
    password_hash VARCHAR(64) NOT NULL,
    recovery_hash VARCHAR(64),                -- salted hash of the recovery email, never the email itself
    recovery_salt VARCHAR(64),                -- per-user salt for recovery_hash
    first_name    VARCHAR(80),                -- optional profile details, learner-supplied
    surname       VARCHAR(80),
    contact_email VARCHAR(200),               -- optional, used for reminders only
    whatsapp      VARCHAR(30),                -- optional, digits/spaces/+ only
    created_at    TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT app_users_username_length_check CHECK (LENGTH(user_id) BETWEEN 3 AND 100)
);

CREATE TABLE IF NOT EXISTS password_resets (
    token_hash  VARCHAR(64) PRIMARY KEY,      -- SHA-256 of the one-time token; the token itself is never stored
    user_id     VARCHAR(100) NOT NULL REFERENCES app_users(user_id) ON DELETE CASCADE,
    expires_at  TIMESTAMP   NOT NULL,
    used_at     TIMESTAMP,
    created_at  TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS checklist_progress (
    user_id      VARCHAR(100) NOT NULL REFERENCES app_users(user_id) ON DELETE CASCADE,
    item_id      VARCHAR(80) NOT NULL,
    completed    INTEGER NOT NULL DEFAULT 0,
    updated_at   TIMESTAMP NOT NULL,
    PRIMARY KEY (user_id, item_id)
);